-- Progression pédagogique (cahier §3.3) : une ligne par utilisateur et par élément du parcours
-- (leçon, quiz, scénario de marché, défi). Le contenu lui-même est versionné dans learning/catalog.json.

CREATE TABLE learning_progress (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    item_type   VARCHAR(20)   NOT NULL,
    item_id     VARCHAR(64)   NOT NULL,
    score       DOUBLE PRECISION,
    points      INTEGER       NOT NULL DEFAULT 0,
    attempts    INTEGER       NOT NULL DEFAULT 0,
    completed   BOOLEAN       NOT NULL DEFAULT FALSE,
    detail      VARCHAR(500),
    created_at  TIMESTAMP(6)  NOT NULL,
    updated_at  TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_learning_progress UNIQUE (user_id, item_type, item_id)
);

CREATE INDEX idx_learning_progress_user ON learning_progress (user_id);
