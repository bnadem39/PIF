-- Schéma initial (état du projet après la phase 0).
-- Sur une base existante créée par Hibernate (ddl-auto=update), Flyway pose une baseline
-- en version 1 (spring.flyway.baseline-on-migrate) et ce script n'est pas rejoué.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(150)   NOT NULL,
    password        VARCHAR(255)   NOT NULL,
    full_name       VARCHAR(255),
    role            VARCHAR(30)    NOT NULL,
    cash_balance    NUMERIC(15, 3) NOT NULL,
    blocked_cash    NUMERIC(15, 3) NOT NULL,
    virtual_balance NUMERIC(15, 3),
    created_at      TIMESTAMP(6)   NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ROLE_ADMIN', 'ROLE_TRADER'))
);

CREATE TABLE positions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT         NOT NULL,
    symbol                 VARCHAR(30)    NOT NULL,
    quantity               INTEGER        NOT NULL,
    average_cost_price     NUMERIC(15, 3) NOT NULL,
    stop_loss_price        NUMERIC(15, 3),
    take_profit_price      NUMERIC(15, 3),
    trailing_stop_distance NUMERIC(15, 3),
    highest_price_seen     NUMERIC(15, 3),
    updated_at             TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_positions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_positions_user_symbol UNIQUE (user_id, symbol)
);

CREATE TABLE order_transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL,
    symbol          VARCHAR(30)    NOT NULL,
    type            VARCHAR(10)    NOT NULL,
    quantity        INTEGER        NOT NULL,
    execution_price NUMERIC(15, 3) NOT NULL,
    fees            NUMERIC(15, 3) NOT NULL,
    realized_pnl    NUMERIC(15, 3),
    simulated_date  VARCHAR(30)    NOT NULL,
    created_at      TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_order_transactions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_order_transactions_type CHECK (type IN ('BUY', 'SELL', 'LIMIT', 'MARKET', 'STOP_LOSS', 'TAKE_PROFIT', 'OCO'))
);

CREATE INDEX idx_order_transactions_user_created ON order_transactions (user_id, created_at);
