-- Scénarios de stress testing (cahier §3.5.1), gérés par l'administrateur.
-- Les chocs sont transmis au service IA (ai/stress) qui projette leur impact sur les banques.

CREATE TABLE stress_scenarios (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                     VARCHAR(40)   NOT NULL,
    name                     VARCHAR(120)  NOT NULL,
    description              VARCHAR(1000),
    rate_shock_bp            NUMERIC(8, 2) NOT NULL,
    equity_drop_pct          NUMERIC(8, 2) NOT NULL,
    unemployment_increase_pp NUMERIC(8, 2) NOT NULL,
    gdp_growth_pct           NUMERIC(8, 2) NOT NULL,
    default_rate_multiplier  NUMERIC(8, 2) NOT NULL,
    asset_quality_downgrade  NUMERIC(8, 2) NOT NULL,
    revenue_drop_pct         NUMERIC(8, 2) NOT NULL,
    preset                   BOOLEAN       NOT NULL,
    created_at               TIMESTAMP(6)  NOT NULL,
    updated_at               TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_stress_scenarios_code UNIQUE (code)
);

