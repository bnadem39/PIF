-- Portefeuille global du joueur : un seul solde pour toutes les salles.
-- Entrer dans une salle débite le prix d'entrée (= capital de jeu de la salle) ; la fin du match
-- recrédite le capital final. Un crédit (dette) permet d'entrer quand le solde est insuffisant ;
-- il est remboursé en priorité sur ce que le joueur récupère en fin de match.

CREATE TABLE player_wallets (
    user_id     BIGINT         PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    balance     NUMERIC(15, 3) NOT NULL,
    debt        NUMERIC(15, 3) NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6)   NOT NULL,
    updated_at  TIMESTAMP(6)   NOT NULL
);

-- Journal des mouvements : une seule ligne par (joueur, salle, type), ce qui empêche
-- de débiter ou de régler deux fois le même match.
CREATE TABLE wallet_transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    room_id        VARCHAR(20),
    type           VARCHAR(20)    NOT NULL,
    amount         NUMERIC(15, 3) NOT NULL,
    balance_after  NUMERIC(15, 3) NOT NULL,
    debt_after     NUMERIC(15, 3) NOT NULL,
    label          VARCHAR(200),
    created_at     TIMESTAMP(6)   NOT NULL,
    CONSTRAINT uk_wallet_tx_room_type UNIQUE (user_id, room_id, type)
);

CREATE INDEX idx_wallet_tx_user ON wallet_transactions (user_id, id);
