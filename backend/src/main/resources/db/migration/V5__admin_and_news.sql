-- Administration (cahier §5) : désactivation de comptes par un administrateur.
ALTER TABLE users ADD COLUMN enabled BOOLEAN NOT NULL DEFAULT TRUE;

-- Actualités financières (cahier §3.4.3 et §5) : saisies par un administrateur avec leur date de publication
-- réelle, puis notées par l'analyse de sentiment du service IA. Elles ne sont visibles dans la simulation qu'à
-- partir de leur date de publication.
CREATE TABLE news_articles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    published_date   VARCHAR(10)   NOT NULL,
    title            VARCHAR(300)  NOT NULL,
    source           VARCHAR(120),
    url              VARCHAR(500),
    body             VARCHAR(4000),
    symbols          VARCHAR(300),
    sentiment_score  DOUBLE PRECISION NOT NULL,
    sentiment_label  VARCHAR(10)   NOT NULL,
    sentiment_terms  VARCHAR(1000),
    created_by       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at       TIMESTAMP(6)  NOT NULL
);

CREATE INDEX idx_news_published ON news_articles (published_date);
